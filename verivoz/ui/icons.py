def _dpr() -> float:
    screen = QGuiApplication.primaryScreen()
    return max(2.0, screen.devicePixelRatio() if screen else 2.0)


def _hex(color) -> str:
    return QColor(color).name()


def pixmap(name: str, color, size: int = 20, stroke: float = 2.0) -> QPixmap:
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
           f'stroke="{_hex(color)}" stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">'
           f'{_PATHS[name]}</svg>')
    if name == "play":
        svg = svg.replace('fill="none"', f'fill="{_hex(color)}"', 1)
    dpr = _dpr()
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    renderer = QSvgRenderer(QByteArray(svg.encode()))
    painter = QPainter(pm)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter)
    painter.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color, size: int = 20, stroke: float = 2.0) -> QIcon:
    return QIcon(pixmap(name, color, size, stroke))


def logo_pixmap(size: int = 64, light: bool = False) -> QPixmap:
    """Logo: blue rounded square with a white sound wave."""
    dpr = _dpr()
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    pm.setDevicePixelRatio(dpr)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    rect = QRectF(0, 0, size, size)
    path = QPainterPath()
    path.addRoundedRect(rect, size * 0.26, size * 0.26)
    if light:
        p.fillPath(path, QColor(255, 255, 255, 46))
        bar_color = QColor("#FFFFFF")
    else:
        grad = QLinearGradient(rect.topLeft(), rect.bottomRight())
        grad.setColorAt(0, QColor("#2F74FF"))
        grad.setColorAt(1, QColor("#1747C9"))
        p.fillPath(path, grad)
        bar_color = QColor("#FFFFFF")
    heights = [0.22, 0.42, 0.68, 0.46, 0.82, 0.54, 0.3]
    n = len(heights)
    bw = size * 0.075
    gap = (size * 0.66 - n * bw) / (n - 1)
    x = size * 0.17
    p.setPen(Qt.PenStyle.NoPen)
    p.setBrush(bar_color)
    for h in heights:
        bh = size * h * 0.78
        p.drawRoundedRect(QRectF(x, (size - bh) / 2, bw, bh), bw / 2, bw / 2)
        x += bw + gap
    p.end()
    return pm


def app_icon() -> QIcon:
    ic = QIcon()
    for s in (16, 24, 32, 48, 64, 128, 256):
        ic.addPixmap(logo_pixmap(s))
    return ic
