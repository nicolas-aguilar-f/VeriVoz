_state = {"lang": "en"}


def set_language(lang: str) -> None:
    _state["lang"] = lang if lang in STRINGS else "en"


def language() -> str:
    return _state["lang"]


def tr(key: str, **kwargs) -> str:
    text = STRINGS.get(_state["lang"], {}).get(key) or STRINGS["en"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text
